import bpy, sys, json, mathutils
sys.path.insert(0, "/home/user/Test-Compa-Git/whiteout/tools/town")
from window_rects import R, D
out = {}
doors = {}
for name, (ox, oy, sc, rects) in R.items():
    bpy.ops.wm.read_factory_settings(use_empty=True)
    bpy.ops.import_scene.gltf(filepath=f"/home/user/Test-Compa-Git/whiteout/assets/env/town_sf/{name}.glb")
    meshes = [o for o in bpy.context.scene.objects if o.type == 'MESH']
    allv = [o.matrix_world @ mathutils.Vector(c) for o in meshes for c in o.bound_box]
    mnx = min(v.x for v in allv); H = max(v.z for v in allv); front = min(v.y for v in allv)
    dg = bpy.context.evaluated_depsgraph_get()
    lst = []
    door = None
    for ri, (x0, y0, x1, y1) in enumerate(rects + ([D[name]] if name in D else [])):
        X0 = mnx + (x0 - ox) / sc / 40.0; X1 = mnx + (x1 - ox) / sc / 40.0
        Y0 = H - (y1 - oy) / sc / 40.0; Y1 = H - (y0 - oy) / sc / 40.0
        hits = []
        for fx in (0.3, 0.5, 0.7):
            for fy in (0.3, 0.5, 0.7):
                p = mathutils.Vector((X0 + (X1 - X0) * fx, front - 5.0, Y0 + (Y1 - Y0) * fy))
                ok, loc, nrm, idx, ob, mt = bpy.context.scene.ray_cast(dg, p, mathutils.Vector((0, 1, 0)), distance=30)
                if ok: hits.append(loc.y)
        ring = []
        for (px, pz) in ((X0-0.15,(Y0+Y1)/2),(X1+0.15,(Y0+Y1)/2),((X0+X1)/2,Y0-0.15),((X0+X1)/2,Y1+0.15),(X0-0.15,Y0-0.15),(X1+0.15,Y1+0.15),(X0-0.15,Y1+0.15),(X1+0.15,Y0-0.15)):
            ok, loc, nrm, idx, ob, mt = bpy.context.scene.ray_cast(dg, mathutils.Vector((px, front - 5.0, pz)), mathutils.Vector((0, 1, 0)), distance=30)
            if ok: ring.append(loc.y)
        if not hits and not ring: continue
        hits.sort(); ring.sort()
        rm = ring[len(ring)//2] if ring else None
        d = hits[len(hits) // 2] if hits else rm
        pass
        # gltf: x, y(up)=blender z, z = -blender y
        if ri == len(rects):
            door = [round((X0 + X1) / 2, 3), round(Y1, 3), round(-d + 0.025, 3), round(X1 - X0, 3), round(Y1 - Y0, 3)]
            continue
        lst.append([round((X0 + X1) / 2, 3), round((Y0 + Y1) / 2, 3), round(-d + 0.025, 3), round(X1 - X0, 3), round(Y1 - Y0, 3)])
    if name == "house_american": lst[5][2] = 3.74
    out[name] = lst
    doors[name] = door
    print("CAST", name, lst)
L = ["extends RefCounted", "## Front (+Z) window openings of the town_sf buildings: [x, y, z, w, h] in model metres.",
     "## Generated by tools/town/window_cast.py (hand-marked rects on ortho renders + raycast depth).", "const WIN := {"]
for k, v in out.items():
    L.append('\t"%s": %s,' % (k, json.dumps(v)))
L.append("}")
L.append("## door openings: [x, top_y, z, w, h]")
L.append("const DOOR := {")
for k, v in doors.items():
    if v: L.append('\t"%s": %s,' % (k, json.dumps(v)))
L.append("}")
open("/home/user/Test-Compa-Git/whiteout/world/town_windows.gd", "w").write("\n".join(L) + "\n")
